using HmmLearn;
using HmmLearn.Tests.Support;

namespace HmmLearn.Tests.Acceptance.Hmm11;

/// <summary>
/// Acceptance tests for the sampling and the statistical properties of the fit of <see cref="MultinomialHmm"/> (ticket
/// HMM-11, criterion C4): Sample draws NTrials independent categorical draws per sample and counts them (every row of the
/// result is a non-negative integer vector that sums to exactly NTrials, the states are in range, and the per-state mean
/// count of each feature is within five standard deviations of NTrials * p); Sample and GenerateSampleFromState are
/// deterministic for a fixed random stream; a fit from a random initialization (InitParams "ste", a fixed RandomState)
/// leaves valid distributions and is reproducible with the same seed; the log likelihood of a single-iteration Fit never
/// decreases by more than 1e-9 relative from one iteration to the next (EM with unit priors).
/// </summary>
public class SamplingAndFitTests
{
    /// <summary>The parameters of the model that generates the data of the tests: the test's own inputs, never oracle
    /// numbers. The transmat is uniform so that the state of every sample is drawn i.i.d. with probability 1/2, which makes
    /// the five-standard-deviation bound a standard independent-samples bound.</summary>
    private static (double[] StartProb, double[,] TransMat, double[,] EmissionProb) TrueParameters()
        => (new double[] { 0.6, 0.4 },
            new double[,] { { 0.5, 0.5 }, { 0.5, 0.5 } },
            new double[,] { { 0.1, 0.4, 0.5 }, { 0.6, 0.3, 0.1 } });

    /// <summary>A model with the test's true parameters (init_params "" : nothing is initialized) and the given
    /// implementation.</summary>
    private static MultinomialHmm TrueModel(Implementation implementation)
    {
        var (startProb, transMat, emissionProb) = TrueParameters();
        var model = new MultinomialHmm(
            2, 10, 1.0, 1.0, DecoderAlgorithm.Viterbi, null, 10, 1e-2, false, "ste", "", implementation);
        model.StartProb = startProb;
        model.TransMat = transMat;
        model.EmissionProb = emissionProb;
        return model;
    }

    /// <summary>The data all the fit tests use: 300 samples in two sequences, generated by the true model with a fixed
    /// random.</summary>
    private static (double[,] X, int[] Lengths) FitData()
    {
        var (x, _) = TrueModel(Implementation.Log).Sample(300, random: new Random(12345));
        return (x, new[] { 150, 150 });
    }

    /// <summary>Every row of the samples is a non-negative integer vector that sums to exactly NTrials, the states are in
    /// range and every state is sampled, and the per-state mean count of each feature is within five standard deviations of
    /// NTrials * p (the standard error of m_s independent multinomial draws, m_s the number of samples of state s).</summary>
    [Fact]
    public void sample_counts_n_trials_per_sample_with_per_state_means_within_five_standard_deviations()
    {
        const int nSamples = 5000;
        const int nTrials = 10;
        var (_, _, emissionProb) = TrueParameters();
        var (x, states) = TrueModel(Implementation.Log).Sample(nSamples, random: new Random(12345));

        Assert.Equal(nSamples, x.GetLength(0));
        Assert.Equal(emissionProb.GetLength(1), x.GetLength(1));
        Assert.Equal(nSamples, states.Length);

        var samplesPerState = new int[emissionProb.GetLength(0)];
        var countsPerState = new long[emissionProb.GetLength(0), emissionProb.GetLength(1)];
        for (var i = 0; i < nSamples; i++)
        {
            var total = 0.0;
            for (var j = 0; j < x.GetLength(1); j++)
            {
                total += x[i, j];
                Assert.True(x[i, j] >= 0.0 && x[i, j] == Math.Floor(x[i, j]),
                    $"sample [{i},{j}] must be a non-negative integer count, got {x[i, j]:R}");
            }
            Close.Equal((double)nTrials, total, $"the total of sample {i}");
            Assert.InRange(states[i], 0, emissionProb.GetLength(0) - 1);
            samplesPerState[states[i]]++;
            for (var j = 0; j < x.GetLength(1); j++)
                countsPerState[states[i], j] += (long)x[i, j];
        }

        for (var s = 0; s < samplesPerState.Length; s++)
            Assert.True(samplesPerState[s] >= 1000,
                $"state {s} was sampled {samplesPerState[s]} times; the uniform transmat gives each state probability 1/2 at every position");

        for (var s = 0; s < emissionProb.GetLength(0); s++)
            for (var j = 0; j < emissionProb.GetLength(1); j++)
            {
                var p = emissionProb[s, j];
                var mean = countsPerState[s, j] / (double)samplesPerState[s];
                var bound = 5.0 * Math.Sqrt((double)nTrials * p * (1.0 - p) / samplesPerState[s]);
                Assert.True(Math.Abs(mean - (double)nTrials * p) <= bound,
                    $"state {s}, feature {j}: mean count {mean} deviates from {nTrials} * {p} by more than 5 standard deviations (bound {bound})");
            }
    }

    /// <summary>Sample is a deterministic function of the random stream: two calls with the same random (or the same
    /// RandomState) give identical observations and states.</summary>
    [Fact]
    public void sample_is_reproducible_with_a_fixed_random_or_random_state()
    {
        var (x1, states1) = TrueModel(Implementation.Log).Sample(37, random: new Random(12345));
        var (x2, states2) = TrueModel(Implementation.Log).Sample(37, random: new Random(12345));
        Close.Equal(x1, x2, "the observations of two samples with the same random");
        Assert.Equal(states1, states2);

        var byState = TrueModel(Implementation.Log);
        byState.RandomState = 12345;
        var (x3, states3) = byState.Sample(37);
        var byState2 = TrueModel(Implementation.Log);
        byState2.RandomState = 12345;
        var (x4, states4) = byState2.Sample(37);
        Close.Equal(x3, x4, "the observations of two samples with the same RandomState");
        Assert.Equal(states3, states4);
    }

    /// <summary>Exposes the protected <see cref="MultinomialHmm.GenerateSampleFromState"/> of the model under test.</summary>
    private sealed class GenerateSampleHarness : MultinomialHmm
    {
        public GenerateSampleHarness(double[,] emissionProb)
            : base(2, 10, 1.0, 1.0, DecoderAlgorithm.Viterbi, null, 1, 1e-2, false, "ste", "", Implementation.Log)
        {
            StartProb = new[] { 0.5, 0.5 };
            TransMat = new double[,] { { 0.5, 0.5 }, { 0.5, 0.5 } };
            EmissionProb = emissionProb;
        }

        public double[] Draw(int state, Random random) => GenerateSampleFromState(state, random);
    }

    /// <summary>GenerateSampleFromState draws NTrials independent categorical draws from the row of the state and counts
    /// them: a degenerate row counts all the trials in its only positive feature.</summary>
    [Fact]
    public void generate_sample_from_state_counts_n_trials_independent_draws()
    {
        var model = new GenerateSampleHarness(new double[,] { { 1.0, 0.0, 0.0 }, { 0.0, 0.5, 0.5 } });
        var nTrials = 10;

        for (var i = 0; i < 100; i++)
        {
            var drawn = model.Draw(0, new Random(12345 + i));
            Assert.True(drawn.Length == 3, "GenerateSampleFromState must return a count vector with one entry per feature");
            Assert.True(Math.Abs(drawn[0] - nTrials) <= 1e-12,
                $"the degenerate row must count all {nTrials} trials in its positive feature, got {drawn[0]:R}");
            Assert.True(drawn[1] == 0.0 && drawn[2] == 0.0,
                $"the degenerate row must count nothing in its zero features, got [{drawn[1]:R}, {drawn[2]:R}]");
        }
    }

    /// <summary>A fit from a random initialization (NIter = 0: initialize and check only) leaves valid distributions and
    /// infers n_features from the data.</summary>
    [Theory]
    [InlineData(Implementation.Log)]
    [InlineData(Implementation.Scaling)]
    public void a_fit_from_a_random_initialization_leaves_valid_distributions(Implementation implementation)
    {
        var (x, lengths) = FitData();
        var model = new MultinomialHmm(
            2, 10, 1.0, 1.0, DecoderAlgorithm.Viterbi, 12345, 0, 1e-2, false, "ste", "ste", implementation);

        model.Fit(x, lengths);

        Assert.True(model.NFeatures == 3, $"n_features: expected 3, got {model.NFeatures}");
        Assert.True(model.StartProb!.All(v => v >= 0.0), "startprob has negative entries");
        Assert.True(Math.Abs(model.StartProb!.Sum() - 1.0) <= 1e-8, "startprob does not sum to 1");
        Assert.True(model.TransMat!.Cast<double>().All(v => v >= 0.0), "transmat has negative entries");
        Assert.True(RowsSumToOne(model.TransMat!), "transmat is not row-stochastic");
        Assert.True(model.EmissionProb!.Cast<double>().All(v => v >= 0.0), "emissionprob has negative entries");
        Assert.True(RowsSumToOne(model.EmissionProb!), "emissionprob is not row-stochastic");
    }

    /// <summary>A fit from a random initialization is reproducible: two models with the same RandomState and the same data
    /// give the same fitted parameters.</summary>
    [Theory]
    [InlineData(Implementation.Log)]
    [InlineData(Implementation.Scaling)]
    public void a_fit_from_a_random_initialization_is_reproducible_with_the_same_seed(Implementation implementation)
    {
        var (x, lengths) = FitData();
        var m1 = new MultinomialHmm(
            2, 10, 1.0, 1.0, DecoderAlgorithm.Viterbi, 12345, 0, 1e-2, false, "ste", "ste", implementation);
        var m2 = new MultinomialHmm(
            2, 10, 1.0, 1.0, DecoderAlgorithm.Viterbi, 12345, 0, 1e-2, false, "ste", "ste", implementation);

        m1.Fit(x, lengths);
        m2.Fit(x, lengths);

        Close.Equal(m1.StartProb!, m2.StartProb!, "startprob");
        Close.Equal(m1.TransMat!, m2.TransMat!, "transmat");
        Close.Equal(m1.EmissionProb!, m2.EmissionProb!, "emissionprob");
        Assert.True(m1.NFeatures == m2.NFeatures, $"n_features: {m1.NFeatures} and {m2.NFeatures} differ");
    }

    /// <summary>The log likelihood never decreases from one single-iteration fit to the next: the first fit
    /// random-initializes, then each further fit runs exactly one EM iteration without re-initializing (unit priors: the
    /// M-step is the MLE one, so the monotonicity of EM applies).</summary>
    [Theory]
    [InlineData(Implementation.Log)]
    [InlineData(Implementation.Scaling)]
    public void the_log_likelihood_never_decreases_from_one_single_iteration_fit_to_the_next(Implementation implementation)
    {
        var (x, lengths) = FitData();
        var model = new MultinomialHmm(
            2, 10, 1.0, 1.0, DecoderAlgorithm.Viterbi, 12345, 1, 1e-2, false, "ste", "ste", implementation);

        model.Fit(x, lengths);
        var logLikelihood = model.Score(x, lengths);

        for (var i = 1; i <= 10; i++)
        {
            model.InitParams = "";
            model.Fit(x, lengths);
            var next = model.Score(x, lengths);
            Assert.True(next >= logLikelihood - 1e-9 * Math.Abs(logLikelihood),
                $"iteration {i} ({implementation}): the log likelihood decreased from {logLikelihood} to {next} (more than 1e-9 relative)");
            logLikelihood = next;
        }
    }

    /// <summary>True when every row of a sums to 1 (within 1e-8).</summary>
    private static bool RowsSumToOne(double[,] a)
    {
        for (var i = 0; i < a.GetLength(0); i++)
        {
            var sum = 0.0;
            for (var j = 0; j < a.GetLength(1); j++)
                sum += a[i, j];
            if (Math.Abs(sum - 1.0) > 1e-8)
                return false;
        }
        return true;
    }
}
