using HmmLearn;
using HmmLearn.Tests.Support;

namespace HmmLearn.Tests.Acceptance.Hmm10;

/// <summary>
/// Acceptance tests for the sampling and the random initialization of <see cref="CategoricalHmm"/> (ticket HMM-10, criterion C4):
/// Sample emits one symbol per sample, in 0 .. n_features - 1, whose frequencies match the emission probabilities (within 5 standard
/// deviations, computed from the test's own inputs); Sample and GenerateSample are deterministic for a fixed random stream; a fit from a
/// random initialization (Dirichlet start and transition rows, uniform emission rows normalized) leaves valid distributions and is
/// reproducible with the same seed; the log likelihood never decreases from one single-iteration EM fit to the next.
/// </summary>
public class SamplingAndFitTests
{
    /// <summary>The parameters of the model that generates the data of the tests: the test's own inputs, never oracle numbers.</summary>
    private static (double[] StartProb, double[,] TransMat, double[,] EmissionProb) TrueParameters()
        => (new double[] { 0.6, 0.4 }, new double[,] { { 0.7, 0.3 }, { 0.4, 0.6 } }, new double[,] { { 0.1, 0.4, 0.5 }, { 0.6, 0.3, 0.1 } });

    /// <summary>A model with the test's true parameters (init_params "" : nothing is initialized) and the given implementation.</summary>
    private static CategoricalHmm TrueModel(Implementation implementation)
    {
        var (startProb, transMat, emissionProb) = TrueParameters();
        var model = new CategoricalHmm(
            2, 1.0, 1.0, 1.0, 3, DecoderAlgorithm.Viterbi, null, 10, 1e-2, false, "ste", "", implementation);
        model.StartProb = startProb;
        model.TransMat = transMat;
        model.EmissionProb = emissionProb;
        return model;
    }

    /// <summary>The data all the fit tests use: 300 samples in two sequences, generated by the true model with a fixed random.</summary>
    private static (double[,] X, int[] Lengths) FitData()
    {
        var (x, _) = TrueModel(Implementation.Log).Sample(300, random: new Random(12345));
        return (x, new[] { 150, 150 });
    }

    /// <summary>Sample emits one symbol per sample in 0 .. n_features - 1, every symbol appears, and the per-state symbol frequencies
    /// are within 5 standard deviations of the corresponding row of the emission probabilities.</summary>
    [Fact]
    public void sample_returns_in_range_symbols_whose_frequencies_match_the_emission_prob()
    {
        const int nSamples = 5000;
        var (_, _, emissionProb) = TrueParameters();
        var (x, states) = TrueModel(Implementation.Log).Sample(nSamples, random: new Random(12345));

        Assert.Equal(nSamples, x.GetLength(0));
        Assert.Equal(1, x.GetLength(1));
        Assert.Equal(nSamples, states.Length);

        var totalCounts = new int[emissionProb.GetLength(1)];
        var countsPerState = new int[emissionProb.GetLength(0), emissionProb.GetLength(1)];
        var samplesPerState = new int[emissionProb.GetLength(0)];
        for (var i = 0; i < nSamples; i++)
        {
            var symbol = (int)x[i, 0];
            Assert.InRange(symbol, 0, emissionProb.GetLength(1) - 1);
            Assert.InRange(states[i], 0, emissionProb.GetLength(0) - 1);
            totalCounts[symbol]++;
            countsPerState[states[i], symbol]++;
            samplesPerState[states[i]]++;
        }

        for (var s = 0; s < emissionProb.GetLength(0); s++)
            Assert.True(samplesPerState[s] >= 1000, $"state {s} was sampled {samplesPerState[s]} times; expected at least 1000");

        for (var s = 0; s < emissionProb.GetLength(0); s++)
            for (var j = 0; j < emissionProb.GetLength(1); j++)
            {
                var p = emissionProb[s, j];
                var frequency = countsPerState[s, j] / (double)samplesPerState[s];
                var bound = 5.0 * Math.Sqrt(p * (1.0 - p) / samplesPerState[s]);
                Assert.True(Math.Abs(frequency - p) <= bound,
                    $"state {s}, symbol {j}: frequency {frequency} deviates from {p} by more than 5 standard deviations (bound {bound})");
            }

        for (var j = 0; j < emissionProb.GetLength(1); j++)
            Assert.True(totalCounts[j] > 0, $"symbol {j} never appeared in the sample");
    }

    /// <summary>Sample is a deterministic function of the random stream: two calls with the same random (or the same RandomState)
    /// give identical observations and states.</summary>
    [Fact]
    public void sample_is_reproducible_with_a_fixed_random_or_random_state()
    {
        var (x1, states1) = TrueModel(Implementation.Log).Sample(37, random: new Random(12345));
        var (x2, states2) = TrueModel(Implementation.Log).Sample(37, random: new Random(12345));
        Close.Equal(x1, x2, "the observations of two samples with the same random");
        Assert.Equal(states1, states2);

        var byState = TrueModel(Implementation.Log);
        byState.RandomState = 12345;
        var (x3, _) = byState.Sample(37);
        var byState2 = TrueModel(Implementation.Log);
        byState2.RandomState = 12345;
        var (x4, _) = byState2.Sample(37);
        Close.Equal(x3, x4, "the observations of two samples with the same RandomState");
    }

    /// <summary>GenerateSample draws one symbol from the row of the state: a degenerate row always draws its only positive symbol,
    /// and 10000 draws from a row follow its probabilities within 5 standard deviations.</summary>
    [Fact]
    public void generate_sample_draws_symbols_from_the_row_of_the_state()
    {
        var degenerate = new double[,] { { 1.0, 0.0, 0.0 } };
        var degenerateRandom = new Random(12345);
        for (var i = 0; i < 1000; i++)
        {
            var drawn = CategoricalEmission.GenerateSample(degenerate, 0, degenerateRandom);
            Assert.True(drawn.Length == 1, "GenerateSample must return a one-element observation");
            Assert.Equal(0.0, drawn[0]);
        }

        var emissionProb = new double[,] { { 0.5, 0.3, 0.2 }, { 0.5, 0.3, 0.2 } };
        var counts = new int[3];
        const int nDraws = 10000;
        var random = new Random(12345);
        for (var i = 0; i < nDraws; i++)
        {
            var drawn = CategoricalEmission.GenerateSample(emissionProb, 1, random);
            Assert.True(drawn.Length == 1, "GenerateSample must return a one-element observation");
            var symbol = (int)drawn[0];
            Assert.InRange(symbol, 0, 2);
            counts[symbol]++;
        }
        for (var j = 0; j < 3; j++)
        {
            var p = emissionProb[1, j];
            var frequency = counts[j] / (double)nDraws;
            var bound = 5.0 * Math.Sqrt(p * (1.0 - p) / nDraws);
            Assert.True(Math.Abs(frequency - p) <= bound,
                $"symbol {j}: frequency {frequency} deviates from {p} by more than 5 standard deviations (bound {bound})");
            Assert.True(counts[j] > 0, $"symbol {j} never appeared");
        }
    }

    /// <summary>A fit from a random initialization (Dirichlet start and transition rows, uniform emission rows normalized) leaves
    /// valid distributions and infers n_features from the data.</summary>
    [Fact]
    public void a_fit_from_a_random_initialization_leaves_valid_distributions()
    {
        var (x, lengths) = FitData();
        var model = new CategoricalHmm(
            2, 1.0, 1.0, 1.0, null, DecoderAlgorithm.Viterbi, 12345, 3, 1e-2, false, "ste", "ste", Implementation.Log);

        model.Fit(x, lengths);

        Assert.True(model.NFeatures == 3, $"n_features: expected 3, got {model.NFeatures}");
        Assert.True(model.StartProb!.All(v => v >= 0.0), "startprob has negative entries");
        Assert.True(Math.Abs(model.StartProb!.Sum() - 1.0) <= 1e-8, "startprob does not sum to 1");
        Assert.True(model.TransMat!.Cast<double>().All(v => v >= 0.0), "transmat has negative entries");
        Assert.True(RowsSumToOne(model.TransMat!), "transmat is not row-stochastic");
        Assert.True(model.EmissionProb!.Cast<double>().All(v => v >= 0.0), "emissionprob has negative entries");
        Assert.True(RowsSumToOne(model.EmissionProb!), "emissionprob is not row-stochastic");
    }

    /// <summary>A fit from a random initialization is reproducible: two models with the same RandomState and the same data give the
    /// same fitted parameters.</summary>
    [Fact]
    public void a_fit_from_a_random_initialization_is_reproducible_with_the_same_seed()
    {
        var (x, lengths) = FitData();
        var m1 = new CategoricalHmm(
            2, 1.0, 1.0, 1.0, null, DecoderAlgorithm.Viterbi, 12345, 3, 1e-2, false, "ste", "ste", Implementation.Log);
        var m2 = new CategoricalHmm(
            2, 1.0, 1.0, 1.0, null, DecoderAlgorithm.Viterbi, 12345, 3, 1e-2, false, "ste", "ste", Implementation.Log);

        m1.Fit(x, lengths);
        m2.Fit(x, lengths);

        Close.Equal(m1.StartProb!, m2.StartProb!, "startprob");
        Close.Equal(m1.TransMat!, m2.TransMat!, "transmat");
        Close.Equal(m1.EmissionProb!, m2.EmissionProb!, "emissionprob");
        Assert.True(m1.NFeatures == m2.NFeatures, $"n_features: {m1.NFeatures} and {m2.NFeatures} differ");
    }

    /// <summary>The log likelihood never decreases from one single-iteration fit to the next: the first fit random-initializes, then
    /// each further fit runs exactly one EM iteration without re-initializing (unit priors : the M-step is the MLE one, so the
    /// monotonicity of EM applies).</summary>
    [Theory]
    [InlineData(Implementation.Log)]
    [InlineData(Implementation.Scaling)]
    public void the_log_likelihood_never_decreases_from_one_single_iteration_fit_to_the_next(Implementation implementation)
    {
        var (x, lengths) = FitData();
        var model = new CategoricalHmm(
            2, 1.0, 1.0, 1.0, null, DecoderAlgorithm.Viterbi, 12345, 1, 1e-2, false, "ste", "ste", implementation);

        model.Fit(x, lengths);
        var logLikelihood = model.Score(x, lengths);

        for (var i = 1; i <= 10; i++)
        {
            model.InitParams = "";
            model.Fit(x, lengths);
            var next = model.Score(x, lengths);
            Assert.True(next >= logLikelihood - 1e-9 * Math.Abs(logLikelihood),
                $"iteration {i} ({implementation}): the log likelihood decreased from {logLikelihood} to {next} (more than 1e-9 relative)");
            logLikelihood = next;
        }
    }

    /// <summary>True when every row of a sums to 1 (within 1e-8).</summary>
    private static bool RowsSumToOne(double[,] a)
    {
        for (var i = 0; i < a.GetLength(0); i++)
        {
            var sum = 0.0;
            for (var j = 0; j < a.GetLength(1); j++)
                sum += a[i, j];
            if (Math.Abs(sum - 1.0) > 1e-8)
                return false;
        }
        return true;
    }
}
